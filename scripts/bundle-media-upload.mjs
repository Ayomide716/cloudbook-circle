// One file for the media-upload function, for pasting into the Supabase dashboard
// (Edge Functions → Deploy a new function). The CLI (`supabase functions deploy media-upload`)
// deploys the source folder directly and doesn't need this.
//   node scripts/bundle-media-upload.mjs
import { build } from "esbuild";

await build({
  entryPoints: ["supabase/functions/media-upload/index.ts"],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  outfile: "supabase/functions/media-upload/dashboard-paste.ts",
  banner: {
    js: "// GENERATED by scripts/bundle-media-upload.mjs from supabase/functions/media-upload/index.ts.\n// Paste this whole file into Supabase → Edge Functions → media-upload. Don't edit it here.\n// @ts-nocheck",
  },
  logLevel: "warning",
});
console.log("wrote supabase/functions/media-upload/dashboard-paste.ts");
